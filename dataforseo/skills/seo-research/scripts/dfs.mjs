#!/usr/bin/env node

// dfs.mjs — generic DataForSEO API v3 client
// Zero dependencies — requires Node 18+ (built-in fetch).
//
// DataForSEO's API is uniform: every endpoint is hit with HTTP Basic auth, a POST
// body that is a JSON ARRAY of task objects, and a JSON response with the same
// envelope (version, status_code, tasks[] -> result[] -> items[]). So one script
// can call ANY endpoint — you only change --endpoint and --payload.
//
// Usage:
//   node dfs.mjs --endpoint <path> [--payload <json> | --payload-file <path> | (stdin)] [options]
//
// Options:
//   --endpoint <path>      API path, e.g. /v3/dataforseo_labs/google/ranked_keywords/live   (REQUIRED)
//   --payload <json>       Request body as a JSON string (array of task objects).
//   --payload-file <path>  Read the request body from a file (use this for complex payloads).
//   (stdin)                If neither --payload nor --payload-file is given (POST only), read body from stdin.
//   --method <GET|POST>    HTTP method (default POST). Use GET for locations/languages and *_get endpoints.
//   --output <path>        Save the full raw JSON response here. Defaults to /tmp/dfs-<endpoint>-<ts>.json.
//   --preview <N>          Include the first N items of tasks[0].result[0].items in the summary (shape check).
//   --sandbox              Use the sandbox host (returns dummy data with identical structure, no charge).
//   --raw                  Print the full raw response JSON to stdout instead of the compact summary.
//
// Env:
//   DATAFORSEO_LOGIN       DataForSEO account login (email).
//   DATAFORSEO_PASSWORD    API password from https://app.dataforseo.com/api-access
//                          (this is generated by DataForSEO — NOT your account password).

import { writeFileSync, mkdirSync, readFileSync } from 'node:fs';
import { dirname } from 'node:path';

const PROD_HOST = 'https://api.dataforseo.com';
const SANDBOX_HOST = 'https://sandbox.dataforseo.com';

// Common DataForSEO status_code values mapped to actionable hints.
const CODE_HINTS = {
  40100: 'Authorization failed — check DATAFORSEO_LOGIN / DATAFORSEO_PASSWORD. The password is the API password from https://app.dataforseo.com/api-access, not your account password.',
  40200: 'Payment required — your account balance is likely empty.',
  40210: 'Insufficient funds — top up your DataForSEO balance.',
  40202: 'Rate limit exceeded (max 2000 requests/minute).',
  40203: 'Daily cost limit exceeded for this account.',
  40209: 'Too many simultaneous queries — reduce concurrency and retry.',
  40207: 'IP not whitelisted for this account.',
  40400: 'Not found — check the --endpoint path against https://docs.dataforseo.com/v3/.',
  40401: 'Task not found (it may have expired; results are stored ~30 days).',
  40501: 'Invalid field in the payload — check parameter names and types against the docs.',
  40502: 'POST data is empty — provide a payload (a JSON array of task objects).',
  40503: 'POST data is invalid — the body must be a JSON array of task objects.',
  50000: 'DataForSEO internal error — retry shortly.',
  50401: 'Internal timeout — the task exceeded the time limit; try a smaller request.',
};

function parseArgs() {
  const argv = process.argv.slice(2);
  const parsed = { method: 'POST' };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === '--sandbox') parsed.sandbox = true;
    else if (a === '--raw') parsed.raw = true;
    else if (a.startsWith('--') && i + 1 < argv.length) parsed[a.slice(2)] = argv[++i];
    else { console.error(`Unknown or malformed argument: ${a}`); process.exit(2); }
  }
  parsed.method = String(parsed.method).toUpperCase();

  if (!parsed.endpoint) {
    console.error('Error: --endpoint is required, e.g. --endpoint /v3/dataforseo_labs/google/ranked_keywords/live');
    process.exit(2);
  }
  if (!parsed.endpoint.startsWith('/')) parsed.endpoint = '/' + parsed.endpoint;

  const login = process.env.DATAFORSEO_LOGIN;
  const password = process.env.DATAFORSEO_PASSWORD;
  if (!login || !password) {
    console.error('Error: DATAFORSEO_LOGIN and DATAFORSEO_PASSWORD environment variables are required.');
    console.error('Set them in your shell profile (~/.bashrc). The password is the API password from');
    console.error('https://app.dataforseo.com/api-access (generated by DataForSEO, not your account password).');
    process.exit(2);
  }
  parsed.login = login;
  parsed.password = password;
  return parsed;
}

function resolveBody(cfg) {
  if (cfg.method === 'GET') return null;
  let raw = cfg.payload;
  if (cfg['payload-file']) raw = readFileSync(cfg['payload-file'], 'utf8');
  if (raw === undefined) raw = readFileSync(0, 'utf8'); // stdin
  raw = (raw || '').trim();
  if (!raw) {
    console.error('Error: no payload provided. Pass --payload, --payload-file, or pipe JSON via stdin.');
    process.exit(2);
  }
  let body;
  try {
    body = JSON.parse(raw);
  } catch (err) {
    console.error(`Error: payload is not valid JSON: ${err.message}`);
    process.exit(2);
  }
  // DataForSEO expects an array of task objects. Wrap a lone object for convenience.
  if (!Array.isArray(body)) body = [body];
  return body;
}

function defaultOutput(endpoint) {
  const slug = endpoint.replace(/^\/v3\//, '').replace(/[^a-z0-9]+/gi, '-').replace(/^-|-$/g, '');
  return `/tmp/dfs-${slug}-${Date.now()}.json`;
}

function summarize(data, endpoint, host, httpStatus, outputFile, previewN) {
  const tasks = Array.isArray(data.tasks) ? data.tasks : [];
  const summary = {
    ok: data.status_code === 20000,
    endpoint,
    host: host.replace('https://', ''),
    http_status: httpStatus,
    status_code: data.status_code,
    status_message: data.status_message,
    cost: data.cost,
    time: data.time,
    tasks_count: data.tasks_count,
    tasks_error: data.tasks_error,
    tasks: tasks.map((t) => {
      const result0 = Array.isArray(t.result) ? t.result[0] : null;
      const items = result0 && Array.isArray(result0.items) ? result0.items : null;
      return {
        id: t.id,
        status_code: t.status_code,
        status_message: t.status_message,
        cost: t.cost,
        result_count: t.result_count,
        items_count: result0 ? (result0.items_count ?? (items ? items.length : undefined)) : undefined,
        total_count: result0 ? result0.total_count : undefined,
      };
    }),
    output_file: outputFile,
  };

  if (previewN > 0) {
    const r0 = tasks[0] && Array.isArray(tasks[0].result) ? tasks[0].result[0] : null;
    if (r0 && Array.isArray(r0.items)) summary.preview = r0.items.slice(0, previewN);
    else if (r0) summary.preview = r0;
  }
  return summary;
}

async function main() {
  const cfg = parseArgs();
  const host = cfg.sandbox ? SANDBOX_HOST : PROD_HOST;
  const url = host + cfg.endpoint;
  const body = resolveBody(cfg);
  const auth = 'Basic ' + Buffer.from(`${cfg.login}:${cfg.password}`).toString('base64');

  const opts = {
    method: cfg.method,
    headers: { Authorization: auth, 'Content-Type': 'application/json' },
  };
  if (body) opts.body = JSON.stringify(body);

  let res;
  try {
    res = await fetch(url, opts);
  } catch (err) {
    console.error(`Network error calling ${url}: ${err.message}`);
    process.exit(1);
  }

  const text = await res.text();
  let data;
  try {
    data = JSON.parse(text);
  } catch {
    console.error(`Non-JSON response (HTTP ${res.status}) from ${url}:`);
    console.error(text.slice(0, 1000));
    process.exit(1);
  }

  const outputFile = cfg.output || defaultOutput(cfg.endpoint);
  mkdirSync(dirname(outputFile), { recursive: true });
  writeFileSync(outputFile, JSON.stringify(data, null, 2));

  // Surface errors clearly. Top-level non-20000 is a hard failure.
  if (data.status_code !== 20000) {
    const hint = CODE_HINTS[data.status_code];
    console.error(`DataForSEO error ${data.status_code}: ${data.status_message}`);
    if (hint) console.error(`Hint: ${hint}`);
    console.error(`Full response saved to ${outputFile}`);
    process.exit(1);
  }

  // Per-task errors (e.g. one keyword batch failed) — warn but don't fail the whole run.
  for (const t of data.tasks || []) {
    if (t.status_code >= 40000) {
      const hint = CODE_HINTS[t.status_code];
      console.error(`Task ${t.id} returned ${t.status_code}: ${t.status_message}${hint ? ` — ${hint}` : ''}`);
    }
  }

  if (cfg.raw) {
    process.stdout.write(JSON.stringify(data, null, 2) + '\n');
    return;
  }

  const previewN = cfg.preview ? parseInt(cfg.preview, 10) : 0;
  const summary = summarize(data, cfg.endpoint, host, res.status, outputFile, previewN);
  process.stdout.write(JSON.stringify(summary, null, 2) + '\n');
  console.error(`Cost: $${data.cost ?? 0} | Full response: ${outputFile}`);
}

main().catch((err) => {
  console.error(`Fatal: ${err.message}`);
  process.exit(1);
});
